"""定义知识库查询规划 Tool 使用的结构化提示词。

该提示词只负责将当前医学问题输出为 single/split/follow_up 查询计划，不安排 Todo 顺序、
不执行检索，也不生成医学答案。``{question}`` 由 rewrite 工具在调用独立结构化 LLM 时填入。
"""

QUERY_REWRITE_PROMPT = (
    "该功能负责‘点’：把一个医学资料问题整理为精确、可检索的查询计划。\n"
    "只返回结构化结果，不解释推理过程。\n\n"
    "规则：\n"
    "1. single：单一知识需求，返回一条保留医学实体、人群、年龄、药物、剂量、时限等限制词的"
    "检索语句。\n"
    "2. split：只有确实需要不同证据的独立问题，才拆成最多六条查询；"
    "不得按问号、句子或回答格式机械拆分。\n"
    "3. follow_up：当前问题是同一方案的补充方面时，优先合并成一条完整查询，"
    "不要拆出剂量、疗程等相互依赖的子问题。\n"
    "4. “只根据原文”“简洁回答”“使用表格”等是回答要求，不得成为查询。\n"
    "5. 不得补充当前问题没有给出的医学事实，也不负责安排检索执行顺序。\n\n"
    "当前问题：{question}"
)
